import java.util.Scanner;

public class IfElse {
  public static void main(String[] args) {

    Scanner sc = new Scanner(system.in);
    int age = sc.nextline();

  if(age>=18) {
    System.out.println("You are eligible to vote:");
  } else {
    System.out.println("You are not eligible to vote:");
  }
    sc.close();
  }
}
    
